def build_officers_module():
    mod_dir = os.path.join(KB_DIR, "5_officers_administration")
    ensure_dir(mod_dir)

    dist_off = load_data_file("district_officers.json")
    trf_data = load_data_file("recent_transfers.json")

    districts = dist_off.get("districts", {})
    transfers = trf_data.get("transfers", [])

    lines = ["# 🏛️ ಕರ್ನಾಟಕ ಜಿಲ್ಲಾಧಿಕಾರಿಗಳು, ಎಸ್ಪಿ ಹಾಗೂ ಪ್ರಮುಖ ಅಧಿಕಾರಿಗಳ ಪಟ್ಟಿ (Karnataka Officers Directory)\n"]
    lines.append("## 📍 31 ಜಿಲ್ಲೆಗಳ ಜಿಲ್ಲಾಧಿಕಾರಿಗಳು & ಪೊಲೀಸ್ ವರಿಷ್ಠಾಧಿಕಾರಿಗಳು (DCs & SPs):\n")

    for k, v in districts.items():
        if not isinstance(v, dict):
            continue
        d_name = v.get("district_kn", k)
        dc = (v.get("dc") or {}).get("name_kn") or (v.get("dc") or {}).get("name_en") or "ಲಭ್ಯವಿಲ್ಲ"
        sp = (v.get("sp") or {}).get("name_kn") or (v.get("sp") or {}).get("name_en") or "ಲಭ್ಯವಿಲ್ಲ"
        ceo = (v.get("zp_ceo") or {}).get("name_kn") or (v.get("zp_ceo") or {}).get("name_en") or "ಲಭ್ಯವಿಲ್ಲ"
        phone = (v.get("dc") or {}).get("phone", "")
        lines.append(f"### {d_name} ಜಿಲ್ಲೆ:")
        lines.append(f"* **ಜಿಲ್ಲಾಧಿಕಾರಿ (DC & DM):** {dc}")
        lines.append(f"* **ಜಿಲ್ಲಾ ಪೊಲೀಸ್ ವರಿಷ್ಠಾಧಿಕಾರಿ (SP):** {sp}")
        lines.append(f"* **ಜಿ.ಪಂ ಮುಖ್ಯ ಕಾರ್ಯನಿರ್ವಾಹಕ ಅಧಿಕಾರಿ (ZP CEO):** {ceo}")
        if phone:
            lines.append(f"* **ದೂರವಾಣಿ:** {phone}")
        lines.append("")

    lines.append("## 🔄 ಇತ್ತೀಚಿನ ಪ್ರಮುಖ ವರ್ಗಾವಣೆ ಆದೇಶಗಳು (Recent Transfer Orders):\n")
    for t in transfers[:50]:
        lines.append(f"* **{t.get('date')}:** {t.get('officer_name_kn', t.get('officer_name_en'))} (ಆದೇಶ: {t.get('order_no')}) — {t.get('summary_kn', t.get('summary_en', ''))}")

    with open(os.path.join(mod_dir, "karnataka_officers_transfers.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

