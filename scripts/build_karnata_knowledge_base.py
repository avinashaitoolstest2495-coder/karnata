def decrypt_payload(encoded_str, secret=SECRET_KEY):
    try:
        binary_str = base64.b64decode(encoded_str)
        decoded_bytes = bytes([b ^ ord(secret[i % len(secret)]) for i, b in enumerate(binary_str)])
        return json.loads(decoded_bytes.decode('utf-8'))
    except Exception as e:
        return None

def load_data_file(filename):
    path = os.path.join(DATA_DIR, filename)
    if not os.path.exists(path):
        return {}
    try:
        with open(path, "r", encoding="utf-8") as f:
            d = json.load(f)
            if isinstance(d, dict) and "payload" in d:
                dec = decrypt_payload(d["payload"])
                return dec if dec else d
            return d
    except Exception as e:
        print(f"Error reading {filename}: {e}")
        return {}

