def apply_guide_to_files(slug, guide_html):
    for base_dir in ['.', 'namma-karnataka']:
        file_path = os.path.join(base_dir, 'districts', f'{slug}.html')
        if not os.path.exists(file_path):
            continue
            
        with open(file_path, 'r', encoding='utf-8') as f_in:
            html = f_in.read()
            
        if '<!-- DISTRICT COMPREHENSIVE GUIDE & ESSAY -->' in html:
            html = re.sub(r'<!-- DISTRICT COMPREHENSIVE GUIDE & ESSAY -->.*?<!-- /DISTRICT COMPREHENSIVE GUIDE -->', guide_html, html, flags=re.DOTALL)
        elif 'class="d-sec district-guide-sec"' in html:
            html = re.sub(r'<div class="d-sec district-guide-sec".*?</div>\s*</div>\s*(?:<!-- /DISTRICT COMPREHENSIVE GUIDE -->)?', guide_html, html, count=1, flags=re.DOTALL)
        else:
            target = '<main class="d-main">'
            if target in html:
                html = html.replace(target, f'{target}\n\n    {guide_html}\n')
            else:
                html = html.replace('</main>', f'\n    {guide_html}\n  </main>')
                
        with open(file_path, 'w', encoding='utf-8') as f_out:
            f_out.write(html)

